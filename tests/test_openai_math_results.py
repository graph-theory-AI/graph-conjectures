"""Integrity checks for data/openai_math_results.json.

The file records catalogue entries that a manuscript of OpenAI's collection
(github.com/openai/math) proves, disproves or advances. It is generated by
scripts/sync_openai_math_results.py from a hand-checked list, so we check that
every match points at a record scraper/build.py renders, that model-generated
claims only ever use the ai-* labels, and that the data and the script agree.
"""

from __future__ import annotations

import json
import os
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
sys.path.insert(0, str(ROOT / "scripts"))

import sync_openai_math_results as sync  # noqa: E402
from conjecture_names import names_by_id  # noqa: E402

RELATION_STATUSES = {
    "resolves": {"ai-proved", "ai-disproved"},
    "implies": {"ai-proved", "ai-disproved"},
    "partial": {None},
}


def _catalogue_ids() -> set[str]:
    ids = {p["slug"] for p in json.loads((DATA / "problems.json").read_text(encoding="utf-8"))}
    counters: dict[str, int] = {}
    for s in json.loads((DATA / "arxiv_conjectures.json").read_text(encoding="utf-8")):
        sid = s.get("safe_id") or s.get("arxiv_id", "").replace("/", "_")
        idx = counters.get(sid, 0)
        counters[sid] = idx + 1
        ids.add(f"{sid}__{idx:02d}")
    ids |= {r["bm_id"] for r in json.loads(
        (DATA / "bondy_murty_conjectures.json").read_text(encoding="utf-8"))}
    ids |= {r["id"] for r in json.loads(
        (DATA / "others_conjectures.json").read_text(encoding="utf-8"))}
    return ids


class OpenAIMathResultsTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.payload = json.loads(
            (DATA / "openai_math_results.json").read_text(encoding="utf-8"))
        cls.results = cls.payload["results"]

    def test_every_match_points_at_a_catalogue_record(self):
        ids = [r["id"] for r in self.results]
        self.assertEqual(len(ids), len(set(ids)))
        self.assertEqual(set(ids) - _catalogue_ids(), set())

    def test_every_match_carries_its_canonical_name(self):
        names = names_by_id()
        for r in self.results:
            with self.subTest(id=r["id"]):
                self.assertEqual(r["name"], names[r["id"]])

    def test_claims_use_only_ai_labels(self):
        for r in self.results:
            with self.subTest(id=r["id"]):
                self.assertIn(r["site_status"], RELATION_STATUSES[r["relation"]])
                self.assertIn(r["match_confidence"], {"high", "medium"})
                self.assertTrue(r["one_line"])
                if r["relation"] == "implies":
                    self.assertTrue(r.get("derivation"), "implications must say why")

    def test_manuscripts_link_pinned_pdfs(self):
        prefix = f"{sync.REPOSITORY_URL}/blob/{self.payload['source_commit']}/preprints/"
        for r in self.results:
            with self.subTest(id=r["id"]):
                self.assertTrue(r["family"].isdigit() and r["family_title"])
                self.assertTrue(r["manuscripts"])
                for m in r["manuscripts"]:
                    self.assertTrue(m["title"])
                    self.assertTrue(m["pdf_url"].startswith(prefix))
                    self.assertTrue(m["pdf_url"].endswith(".pdf"))
                self.assertEqual("lean_scope_url" in r,
                                 any(m["lean"] for m in r["manuscripts"]))

    def test_data_matches_the_curated_list(self):
        self.assertEqual([r["id"] for r in self.results],
                         [m["id"] for m in sync.MATCHES])
        for r, m in zip(self.results, sync.MATCHES):
            with self.subTest(id=r["id"]):
                for key in ("relation", "match_confidence", "one_line", "family"):
                    self.assertEqual(r[key], m[key])
                self.assertEqual(r["site_status"], m.get("site_status"))
                self.assertEqual(r.get("derivation"), m.get("derivation"))
                self.assertEqual(r.get("caveats"), m.get("caveats"))
                self.assertEqual(len(r["manuscripts"]), len(m["manuscripts"]))

    def test_source_checkout_matches_checked_in_data(self):
        source = Path(os.environ.get("OPENAI_MATH_DIR", ROOT.parent / "openai-math"))
        if not (source / "CONTENTS.md").is_file():
            self.skipTest("no openai/math checkout (set OPENAI_MATH_DIR)")
        self.assertEqual(sync.collect(source), self.payload)


if __name__ == "__main__":
    unittest.main()
